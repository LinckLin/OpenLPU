  // --------------------------------------------------------------------------
  // rope_sincos(x): returns {cos, sin} as fp32 for angle x (any fp32, |x|≤8192).
  // Cody-Waite two-part reduction to [0,2π), then cubic Hermite interpolation
  // on the 1024-entry sin/cos table (table + degree-3 polynomial in the
  // sub-interval offset h, spec 04 §3.3 LUT+polynomial style).  Hermite error
  // ~ h^4/384 ~ 1e-12 rad, fp32-op truncation ~1e-7 absolute.
  // --------------------------------------------------------------------------
  function automatic logic [63:0] rope_sincos(input logic [31:0] x);
    logic [31:0] nf, r, u, f, h;
    logic [31:0] n2pi_hi, n2pi_lo;
    logic [7:0] e;
    integer n, i, shf;
    logic [31:0] sin0, cos0;
    logic [31:0] t1, t2, t3, t4;
    logic [31:0] u1, u2, u3, u4;
    logic [31:0] res_sin, res_cos;

    // Cody-Waite two-part reduction to [-π, π], then fold into [0, 2π).
    nf = fp32_mul(x, INV_2PI);
    n  = $signed(f32_to_i32_rne(nf));
    n2pi_hi = fp32_mul(i32_to_f32(32'(n)), TWO_PI_HI);
    n2pi_lo = fp32_mul(i32_to_f32(32'(n)), TWO_PI_LO);
    r = fp32_sub(x, n2pi_hi);
    r = fp32_sub(r, n2pi_lo);
    if (r[31]) r = fp32_add(fp32_add(r, TWO_PI_HI), TWO_PI_LO);

    // LUT index u = r * N/(2π) ∈ [0, N); i = floor(u), f = u - i ∈ [0,1).
    u = fp32_mul(r, N_OVER_2PI);
    e = u[30:23];
    if (e < 8'd127) begin
      i = 0;
      f = u;
    end else begin
      shf = 8'd150 - e;
      i = int'({1'b1, u[22:0]} >> shf);
      f = fp32_sub(u, i32_to_f32(32'(i)));
    end

    sin0 = ROPE_LUT_SIN[i];
    cos0 = ROPE_LUT_COS[i];
    h = fp32_mul(f, 32'h3BC90FDB);  // 2π/N

    // sin(xi+h) = sin_i + h*cos_i - h^2*sin_i/2 - h^3*cos_i/6
    t1 = fp32_mul(sin0, F_HALF);
    t2 = fp32_mul(cos0, 32'h3E2AAAAB);  // 1/6
    t3 = fp32_add(t1, fp32_mul(h, t2));
    t4 = fp32_sub(cos0, fp32_mul(h, t3));
    res_sin = fp32_add(sin0, fp32_mul(h, t4));

    // cos(xi+h) = cos_i - h*sin_i - h^2*cos_i/2 + h^3*sin_i/6
    u1 = fp32_mul(cos0, F_HALF);
    u2 = fp32_mul(sin0, 32'h3E2AAAAB);  // 1/6
    u3 = fp32_sub(u1, fp32_mul(h, u2));
    u4 = fp32_add(sin0, fp32_mul(h, u3));
    res_cos = fp32_sub(cos0, fp32_mul(h, u4));

    rope_sincos = {res_cos, res_sin};
  endfunction

